"""Rebuild Michael's v0.2 torch model from the compiled ONNX (weights dequantized / mapped), verify with a
zero-noise parity check against a patched ONNX (zeros noise -> harmonics-only output), and if asked, run the
FIX H export. usage: python scripts/michael_rebuild.py [--export]

Weight sources:
  * plain torch-named tensors (int8 quantized -> DequantizeLinear, fp16 -> Cast);
  * anonymous MatMul weights mapped by the consuming node's name (bert layers keep ALBERT's structure,
    head pw1/pw2/out/out_b by block index); MatMul stores Linear weights transposed, Gemm does not;
  * the gain matrices M / Mb from the '/head/MatMul' Constant inputs (stored as M.T);
  * STFT/window buffers are regenerated by the modules themselves (same construction formulas).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, '.stubs'))
sys.path.insert(0, os.path.join(ROOT, 'paradee_ms'))
sys.path.insert(0, os.path.join(ROOT, 'g2p'))
os.chdir(ROOT)

import numpy as np
import onnx
from onnx import numpy_helper
import torch
import torch.nn as nn

m = onnx.load('runs/michael_v02.onnx')
g = m.graph

# ---- 1. value map: initializers + dequant/cast chain ----
vals = {i.name: numpy_helper.to_array(i) for i in g.initializer}
for _ in range(4):
    changed = False
    for n in g.node:
        if n.op_type == 'DequantizeLinear' and all(i in vals for i in n.input[:3]) and n.output[0] not in vals:
            q, s, z = (vals[n.input[0]], vals[n.input[1]], vals[n.input[2]])
            ax = next(a.i for a in n.attribute if a.name == 'axis')
            shape = [1] * q.ndim; shape[ax] = -1
            vals[n.output[0]] = (q.astype(np.float32) - z.astype(np.float32).reshape(shape)) * s.astype(np.float32).reshape(shape)
            changed = True
        elif n.op_type == 'Cast' and n.input[0] in vals and n.output[0] not in vals:
            to = next(a.i for a in n.attribute if a.name == 'to')
            if to == 1 and vals[n.input[0]].dtype != np.float32:
                vals[n.output[0]] = vals[n.input[0]].astype(np.float32)
                changed = True
    if not changed:
        break

SUF = ('.weight', '.bias', '.style', '.gamma', '.beta', '.weight_orig', '.fwd', '.inv', '.w2', '.M', '.Mb', '.window', '.wb')
sd = {}
for k, v in vals.items():
    if k.endswith(SUF) and v.dtype == np.float32 and 'st.fwd' not in k and 'st.inv' not in k:
        sd[k] = torch.from_numpy(np.array(v, np.float32, copy=True))
print(len(sd), 'torch-named tensors')

# ---- 2. anonymous MatMul/Gemm weights by consumer node name ----
prod = {o: n for n in g.node for o in n.output}


def anon_of(n):
    for i in n.input:
        if i.startswith('onnx::') and not i.startswith(('onnx::LSTM', 'onnx::Expand')) and i in prod:
            pn = prod[i]
            if pn.op_type == 'DequantizeLinear' and pn.input[0] in vals:
                return vals[pn.output[0]]
    return None


def lin(node_name, torch_name, transpose=True):
    n = next((n for n in g.node if n.name == node_name), None)
    if n is None:
        return False
    w = anon_of(n)
    if w is None:
        return False
    sd[torch_name] = torch.from_numpy(np.array(w.T if transpose else w, np.float32, copy=True))
    return True


n_ok = 0
n_ok += lin('/bert/encoder/embedding_hidden_mapping_in/MatMul', 'ts.bert.encoder.embedding_hidden_mapping_in.weight')
for nm in g.node:
    mm = re.match(r'/bert/encoder/albert_layer_groups\.(\d+)/albert_layers\.(\d+)/(.+)/MatMul$', nm.name)
    if mm and lin(nm.name, f'ts.bert.encoder.albert_layer_groups.{mm.group(1)}.albert_layers.{mm.group(2)}.{mm.group(3).replace("/", ".")}.weight'):
        n_ok += 1
for nm in g.node:
    mm = re.match(r'/head/blocks\.(\d+)/(pw1|pw2)/MatMul$', nm.name)
    if mm and lin(nm.name, f'vd.head.blocks.{mm.group(1)}.{mm.group(2)}.weight'):
        n_ok += 1
n_ok += lin('/head/out/MatMul', 'vd.head.out.weight')
n_ok += lin('/head/out_b/MatMul', 'vd.head.out_b.weight')
n_ok += lin('/bert_encoder/MatMul', 'ts.bert_encoder.weight')
n_ok += lin('/duration_proj/linear_layer/MatMul', 'ts.predictor.duration_proj.linear_layer.weight')
n_ok += lin('/asr_proj/asr_proj.0/MatMul', 'ts.asr_proj.0.weight')
n_ok += lin('/asr_proj/asr_proj.2/MatMul', 'ts.asr_proj.2.weight')
# lstms fc + style/speaker Gemms keep torch orientation
for nm in g.node:
    mm = re.match(r'/lstms\.(\d+)/fc/Gemm$', nm.name)
    if mm and lin(nm.name, f'ts.predictor.text_encoder.lstms.{mm.group(1)}.fc.weight', transpose=False):
        n_ok += 1
# LSTM nodes: W (input-hidden), R (hidden-hidden), B (both biases); bidirectional stacks 2 directions
for n in g.node:
    if n.op_type != 'LSTM':
        continue
    W, R, B = (vals[prod[i].output[0]] for i in n.input[1:4])
    owner = None
    mm = re.match(r'/lstms\.(\d+)/', n.name)
    if mm:
        owner = f'ts.predictor.text_encoder.lstms.{mm.group(1)}'
    if owner is None:
        owner = {'/lstm': 'ts.predictor.lstm', '/lstm_1': 'ts.text_encoder.lstm',
                 '/shared': 'ts.predictor.shared'}.get(n.name.rsplit('/', 1)[0])
    if owner is None:
        print('LSTM without owner:', n.name); continue
    dirs = W.shape[0]
    for d, suf in enumerate(['', '_reverse']):
        if d >= dirs:
            break
        def gates(a, hdim):
            # ONNX LSTM gate order is i, o, f, c; torch is i, f, g, o
            a = a.reshape(4, hdim, -1)
            return a[[0, 2, 3, 1]].reshape(4 * hdim, -1)
        hdim = R[d].shape[1]
        sd[owner + '.weight_ih_l0' + suf] = torch.from_numpy(np.array(gates(W[d], hdim), np.float32, copy=True))
        sd[owner + '.weight_hh_l0' + suf] = torch.from_numpy(np.array(gates(R[d], hdim), np.float32, copy=True))
        b_ih, b_hh = B[d][:B.shape[1] // 2], B[d][B.shape[1] // 2:]
        sd[owner + '.bias_ih_l0' + suf] = torch.from_numpy(np.array(np.concatenate([b_ih[0:hdim], b_ih[2 * hdim:3 * hdim], b_ih[3 * hdim:], b_ih[hdim:2 * hdim]]), np.float32, copy=True))
        sd[owner + '.bias_hh_l0' + suf] = torch.from_numpy(np.array(np.concatenate([b_hh[0:hdim], b_hh[2 * hdim:3 * hdim], b_hh[3 * hdim:], b_hh[hdim:2 * hdim]]), np.float32, copy=True))
    n_ok += 1
print(n_ok, 'anonymous tensors mapped')

# gain matrices M / Mb: Constants feeding the post-reshape MatMuls in the head (non-persistent buffers:
# keep them out of the state_dict, assign straight onto the module after loading)
head_mms = [n for n in g.node if n.op_type == 'MatMul' and n.name.startswith('/head/MatMul')]
consts_by_out = {o: n for n in g.node if n.op_type == 'Constant' for o in n.output}
GAINS = {}
for n in head_mms:
    for i in n.input:
        cn = prod.get(i)
        if cn is not None and cn.op_type == 'Constant':
            arr = numpy_helper.to_array(cn.attribute[0].t)
            GAINS.setdefault(n.name, []).append(arr)
GAINS = sorted(GAINS.items())
assert len(GAINS) >= 2, GAINS
M, MB = GAINS[0][1][0].T, GAINS[-1][1][0].T          # [80,301] warp matrix and [24,76] burst warp
print('M', M.shape, 'Mb', MB.shape, 'from', GAINS[0][0], GAINS[-1][0])
sd.pop('vd.head.M', None); sd.pop('vd.head.Mb', None)

# ---- 3. load into the modules ----
from student import TextStudent
from vhead import VDecoder, SR, FHOP  # noqa: F401
from torch.nn.utils import remove_weight_norm
from torch.nn.utils.parametrize import is_parametrized, remove_parametrizations


def strip(mod):
    for x in mod.modules():
        try:
            remove_weight_norm(x)
        except Exception:
            pass
        if is_parametrized(x, 'weight'):
            try:
                remove_parametrizations(x, 'weight', leave_parametrized=True)
            except Exception:
                pass


ts = TextStudent('s+mlp').eval()
vd = VDecoder(head='v2').eval()
strip(ts); strip(vd)
for label, mod in (('ts', ts), ('vd', vd)):
    sub = {k[len(label) + 1:]: v for k, v in sd.items() if k.startswith(label + '.')}
    miss, unexp = mod.load_state_dict(sub, strict=False)
    miss = [x for x in miss if 'pooler' not in x]      # pooler is not in the graph and not used
    print(label, 'missing:', miss[:6], '| unexpected:', list(unexp)[:6])
    assert not miss and not unexp, f'{label} state_dict mismatch'
vd.head.M.copy_(torch.from_numpy(np.array(M, np.float32, copy=True)))
vd.head.Mb.copy_(torch.from_numpy(np.array(MB, np.float32, copy=True)))

# ---- 4. zero-noise parity: patched ONNX (zeros noise -> harmonics only) vs torch head with noise=0 ----
import onnxruntime as ort
import soundfile as sf

m2 = onnx.load('runs/michael_v02.onnx')
g2 = m2.graph
rn = next(n for n in g2.node if n.op_type == 'RandomNormalLike')
# run the ORIGINAL model once with the noise tensor exposed, to learn its exact shape for this input,
# then bake a zeros constant of that shape (zero noise -> harmonics-only output)
m_probe = onnx.load('runs/michael_v02.onnx')
g_probe = m_probe.graph
g_probe.output.append(onnx.helper.make_tensor_value_info(rn.output[0], onnx.TensorProto.FLOAT, None))
p_probe = 'runs/michael_v02_probe.onnx'
onnx.save(m_probe, p_probe)
sess_p = ort.InferenceSession(p_probe, providers=['CPUExecutionProvider'])
from ms_g2p import G2P
from ms_norm import normalize

g2p = G2P(stress=False, r='r', diph='glide', final_a='a')
text = 'Selamat pagi, ini ujian suara Michael versi baru.'
ids = torch.tensor([g2p.tokens(g2p(normalize(text)))], dtype=torch.long)
outs = sess_p.run(None, {'input_ids': ids.numpy(), 'speed': np.ones(1, np.float32)})
noise_shape = outs[1].shape
print('noise shape for this input:', noise_shape)
pos = next(i for i, n in enumerate(g2.node) if n.name == '/head/Mul_9') + 1
g2.node.remove(rn)
g2.initializer.append(numpy_helper.from_array(np.zeros(noise_shape, np.float32), 'zero_noise_const'))
g2.node.insert(pos, onnx.helper.make_node('Identity', ['zero_noise_const'], [rn.output[0]]))
onnx.checker.check_model(m2)
p_zero = 'runs/michael_v02_zeronoise.onnx'
onnx.save(m2, p_zero)
sess = ort.InferenceSession(p_zero, providers=['CPUExecutionProvider'])

y_onnx = sess.run(None, {'input_ids': ids.numpy(), 'speed': np.ones(1, np.float32)})[0][0]

with torch.no_grad():
    t, p, s = ts, ts.predictor, ts.style
    d_en = t.bert_encoder(t.bert(ids, attention_mask=torch.ones_like(ids))).transpose(-1, -2)
    x, T = d_en, ids.shape[1]
    sx = s[:, :, None].expand(-1, -1, T)
    x = torch.cat([x, sx], 1)
    for b in p.text_encoder.lstms:
        if isinstance(b, nn.LSTM):
            x = b(x.transpose(-1, -2))[0].transpose(-1, -2)
        else:
            x = torch.cat([b(x.transpose(-1, -2), s).transpose(-1, -2), sx], 1)
    d = x.transpose(-1, -2)
    dur = torch.sigmoid(p.duration_proj(p.lstm(d)[0])).sum(-1)[0]
    e = t.text_encoder
    h = e.embedding(ids).transpose(1, 2)
    for c in e.cnn:
        h = c(h)
    asr = t.asr_proj(e.lstm(h.transpose(1, 2))[0]).transpose(-1, -2)
    n_ = torch.clamp(torch.round(dur), min=1).long()
    end = torch.cumsum(n_, 0); start = end - n_
    f = torch.arange(int(end[-1]))[None]
    aln = ((f >= start[:, None]) & (f < end[:, None])).float()[None]
    F0, N = p.F0Ntrain(d.transpose(-1, -2) @ aln, s)
    v = vd
    F0c, Nn = v.F0_conv(F0.unsqueeze(1)), v.N_conv(N.unsqueeze(1))
    xh = v.encode(torch.cat([asr @ aln, F0c, Nn], 1), v.style)
    asr_res = v.asr_res(asr @ aln); res = True
    for block in v.decode:
        if res:
            xh = torch.cat([xh, asr_res, F0c, Nn], 1)
        xh = block(xh, v.style)
        if block.upsample_type != 'none':
            res = False
    hd = v.head
    B, _, nf = xh.shape
    Tt = nf * hd.up
    z = hd.norm0(hd.inp(xh).transpose(1, 2)).transpose(1, 2)
    for b in hd.blocks:
        z = b(z)
    hn = hd.norm1(z.transpose(1, 2))
    o = hd.out(hn).view(1, Tt, hd.C * hd.G + 1)
    o = torch.cat([o, o[:, -1:]], 1)
    gg = (o[..., :-1].reshape(1, Tt + 1, hd.C, hd.G) @ hd.M.T).permute(0, 2, 3, 1)
    gh, gn = torch.exp(gg[:, 0].clamp(max=6)), torch.exp(gg[:, 3].clamp(max=6))
    u = torch.complex(gg[:, 1], gg[:, 2]); u = u / u.abs().clamp_min(1e-4)
    from vhead import sine_bank
    ee, cyc, uv = sine_bank(F0, hd.K, None)
    E = hd.stft(ee)
    noise = torch.zeros(1, nf * FHOP)
    Nz0 = hd.stft(noise)
    Nm = [hd.stft(noise * uv * fn(2 * torch.pi * mm * cyc)) for mm in range(1, hd.mod + 1) for fn in (torch.cos, torch.sin)]
    f0raw = torch.cat([F0.repeat_interleave(hd.up, 1), F0[:, -1:]], 1)
    f0f = f0raw.clamp_min(60)
    fr = torch.linspace(0, SR / 2, hd.nb)[None, :, None]
    ratio = fr / f0f[:, None]
    shift = 0.5 * torch.tanh(o[..., -1])[:, None]
    Nz = Nz0 + sum(gg[:, 4 + j] * Nm[j] for j in range(len(Nm)))
    Hh = gh * u * torch.polar(torch.ones_like(ratio), 2 * torch.pi * ratio * shift)
    yh = torch.istft(E * Hh, hd.n_fft, hd.hop, window=hd.window, length=nf * FHOP)
    yn = torch.istft(Nz * gn, hd.n_fft, hd.hop, window=hd.window, length=nf * FHOP)
    if hd.burst:
        gb = torch.exp((hd.out_b(hn).view(1, nf * 4, hd.Gb) @ hd.Mb.T).clamp(max=6)).transpose(1, 2)
        gb = torch.cat([gb, gb[..., -1:]], -1)
        Nb = torch.stft(noise.flip(-1), 150, 75, window=hd.wb, return_complex=True)
        yn = yn + torch.istft(Nb * gb, 150, 75, window=hd.wb, length=nf * FHOP)
    y_t = (yh + yn).squeeze().numpy()

L = min(len(y_onnx), len(y_t))
df = np.abs(y_onnx[:L] - y_t[:L])
print(f'zero-noise parity: max diff {df.max():.4f}, rms diff {np.sqrt((df ** 2).mean()):.5f} | '
      f'lengths {len(y_onnx)} vs {len(y_t)} | signal rms {np.sqrt((y_t ** 2).mean()):.4f}')
sf.write('runs/michael_zeronoise_torch.wav', y_t, SR)

# ---- 5. save the reconstructed weights for the FIX H export ----
if '--export' in sys.argv:
    torch.save({'ts': {k: v for k, v in sd.items() if k.startswith('ts.')},
                'vd': {k: v for k, v in sd.items() if k.startswith('vd.')},
                'M': torch.from_numpy(np.array(M, np.float32, copy=True)),
                'Mb': torch.from_numpy(np.array(MB, np.float32, copy=True))},
               'runs/michael_v02_rebuilt.pt')
    print('saved runs/michael_v02_rebuilt.pt')
